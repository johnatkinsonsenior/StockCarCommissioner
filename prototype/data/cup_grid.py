def _shop(
    name,
    manufacturer,
    car_rating,
    crew_rating,
    reliability,
    starting_budget,
    owner_name,
    personality,
    wealth,
    patience,
    priority,
    prestige,
    engineering,
):
    return Team(
        name=name,
        manufacturer=manufacturer,
        car_rating=car_rating,
        crew_rating=crew_rating,
        reliability=reliability,
        starting_budget=starting_budget,
        owner=Owner(
            name=owner_name,
            personality=personality,
            wealth=wealth,
            patience=patience,
            priority=priority,
        ),
        prestige=prestige,
        engineering=engineering,
    )


def _seat(
    name,
    team_name,
    age,
    speed,
    consistency,
    aggression,
    personality,
    rival,
    popularity,
    salary,
    contract_years,
    **extra
):
    return Driver(
        name=name,
        team_name=team_name,
        age=age,
        speed=speed,
        consistency=consistency,
        aggression=aggression,
        personality=personality,
        rival=rival,
        popularity=popularity,
        salary=salary,
        contract_years=contract_years,
        **extra
    )


